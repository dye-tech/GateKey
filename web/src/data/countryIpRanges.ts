// All countries sorted by name
export const COUNTRIES_SORTED = [...COUNTRY_IP_DATA].sort((a, b) =>
  a.name.localeCompare(b.name)
)

// Get country by code
export function getCountryByCode(code: string): CountryIpData | undefined {
  return COUNTRY_IP_DATA.find(c => c.code.toLowerCase() === code.toLowerCase())
}

// Search countries by name or code
export function searchCountries(query: string): CountryIpData[] {
  const q = query.toLowerCase().trim()
  if (!q) return COUNTRIES_SORTED
  return COUNTRIES_SORTED.filter(c =>
    c.name.toLowerCase().includes(q) ||
    c.code.toLowerCase().includes(q)
  )
}
